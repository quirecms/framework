<?php

declare(strict_types=1);

namespace Quire\Content\Permalink;

use Doctrine\DBAL\Connection;
use Quire\Content\Content;
use Quire\Content\Permalink\Internal\PermalinkSettings;
use Quire\Content\Type\Capability;
use Quire\Content\Type\ContentTypeRegistry;
use Quire\Settings\Event\SettingChanged;
use Quire\Settings\Settings;
use Quire\Settings\SettingsSchema;
use Symfony\Component\EventDispatcher\Attribute\AsEventListener;
use Symfony\Component\Routing\Generator\UrlGeneratorInterface;
use Symfony\Contracts\Service\ResetInterface;

/**
 * The URLs of content items, listings and the homepage, following the site's permalink settings.
 *
 * URLs are generated by the router, so they include the prefix Quire is mounted under (the
 * "quire.routing.prefix" option) and the base path of the application.
 *
 *     $permalinks->url($post);                 // "/blog/hello-world"
 *     $permalinks->listingUrl('post', page: 2); // "/blog?page=2"
 *
 * @api
 */
#[AsEventListener(event: SettingChanged::class, method: 'reset')]
final class Permalinks implements ResetInterface
{
    public const string CONTENT_ROUTE = 'quire_content';

    public const string HOME_ROUTE = 'quire_home';

    private const string UUID_PATTERN = '/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/';

    /** @var array<string, PermalinkPattern> Loaded once per request */
    private array $patterns = [];

    /** @var array{?string}|null The homepage's content item, once looked up */
    private ?array $homepageId = null;

    public function __construct(
        private readonly ContentTypeRegistry $types,
        private readonly Settings $settings,
        private readonly SettingsSchema $schema,
        private readonly UrlGeneratorInterface $urls,
        private readonly Connection $connection,
    ) {
    }

    /**
     * The type's current pattern. A stored pattern that's no longer valid (e.g. the type stopped being
     * hierarchical) falls back to the type's default.
     */
    public function pattern(string $type): PermalinkPattern
    {
        if (isset($this->patterns[$type])) {
            return $this->patterns[$type];
        }

        $definition = $this->types->get($type);
        $hierarchical = $definition->has(Capability::HIERARCHICAL);

        try {
            $pattern = PermalinkPattern::parse($this->settings->getString(PermalinkSettings::PERMALINK_PREFIX.$type), $hierarchical);
        } catch (\InvalidArgumentException) {
            $pattern = PermalinkPattern::parse($definition->permalink, $hierarchical);
        }

        return $this->patterns[$type] = $pattern;
    }

    /**
     * Every type's pattern, in the order to try them when resolving a URL: most specific first.
     *
     * @return array<string, PermalinkPattern> By type
     */
    public function patterns(): array
    {
        $patterns = [];

        foreach (array_keys($this->types->all()) as $type) {
            $patterns[$type] = $this->pattern($type);
        }

        uasort($patterns, static fn (PermalinkPattern $a, PermalinkPattern $b): int => $b->specificity() <=> $a->specificity());

        return $patterns;
    }

    /**
     * The item's URL path relative to where Quire is mounted, e.g. "/blog/hello-world"; "/" for the homepage.
     */
    public function path(Content $content): string
    {
        if ($content->id === $this->homepageId()) {
            return '/';
        }

        $date = ($content->publishedAt ?? $content->createdAt)->setTimezone(new \DateTimeZone(date_default_timezone_get()));

        return $this->pattern($content->type)->generate([
            'slug' => $content->slug,
            'path' => $content->path,
            'id' => $content->id,
            'year' => $date->format('Y'),
            'month' => $date->format('m'),
            'day' => $date->format('d'),
        ]);
    }

    /**
     * @param int $referenceType One of the {@see UrlGeneratorInterface} constants, e.g. ABSOLUTE_URL
     */
    public function url(Content $content, int $referenceType = UrlGeneratorInterface::ABSOLUTE_PATH): string
    {
        return $this->generate($this->path($content), [], $referenceType);
    }

    /**
     * The path of the type's listing relative to where Quire is mounted: "/" when the homepage shows it,
     * null when the type has none.
     */
    public function listingPath(string $type): ?string
    {
        if ('listing' === $this->settings->getString('site.homepage') && $type === $this->settings->getString('site.homepage_listing')) {
            return '/';
        }

        return $this->configuredListingPath($type);
    }

    /**
     * The listing path set for the type (e.g. "/blog"), even when the homepage shows the listing instead.
     *
     * @internal
     */
    public function configuredListingPath(string $type): ?string
    {
        $key = PermalinkSettings::LISTING_PREFIX.$type;
        $this->types->get($type);
        $path = $this->schema->has($key) ? $this->settings->get($key) : null;

        return \is_string($path) && '' !== $path ? $path : null;
    }

    /**
     * @throws \LogicException when the type has no listing
     */
    public function listingUrl(string $type, int $page = 1, int $referenceType = UrlGeneratorInterface::ABSOLUTE_PATH): string
    {
        $path = $this->listingPath($type) ?? throw new \LogicException(\sprintf('The content type "%s" has no list. Set one with the setting "%s".', $type, PermalinkSettings::LISTING_PREFIX.$type));

        return $this->generate($path, $page > 1 ? ['page' => $page] : [], $referenceType);
    }

    public function homeUrl(int $referenceType = UrlGeneratorInterface::ABSOLUTE_PATH): string
    {
        return $this->generate('/', [], $referenceType);
    }

    /**
     * The URL of a path relative to where Quire is mounted, e.g. "/about" becomes "/cms/about" when Quire
     * is mounted under "/cms".
     */
    public function pathUrl(string $path, int $referenceType = UrlGeneratorInterface::ABSOLUTE_PATH): string
    {
        $query = parse_url($path, \PHP_URL_QUERY);
        $url = $this->generate('/'.trim((string) parse_url($path, \PHP_URL_PATH), '/'), [], $referenceType);

        return \is_string($query) && '' !== $query ? $url.'?'.$query : $url;
    }

    /**
     * ID of the content item the homepage shows, when it shows one.
     */
    public function homepageId(): ?string
    {
        if (null !== $this->homepageId) {
            return $this->homepageId[0];
        }

        $page = 'page' === $this->settings->getString('site.homepage') ? $this->settings->get('site.homepage_page') : null;
        $id = null;

        if (\is_string($page) && 1 === preg_match(self::UUID_PATTERN, $page)) {
            $id = $page;
        } elseif (\is_string($page) && '' !== $page) {
            $found = $this->connection->fetchOne(
                "SELECT id FROM quire.content WHERE type = 'page' AND path = ? AND deleted_at IS NULL ORDER BY locale = ? DESC, created_at LIMIT 1",
                [trim($page, '/'), $this->settings->getString('site.locale')],
            );
            $id = \is_string($found) ? $found : null;
        }

        $this->homepageId = [$id];

        return $id;
    }

    /**
     * Forgets what was loaded for this request, e.g. after a setting changed.
     */
    public function reset(): void
    {
        $this->patterns = [];
        $this->homepageId = null;
    }

    /**
     * @param array<string, int|string> $query
     */
    private function generate(string $path, array $query, int $referenceType): string
    {
        return '/' === $path
            ? $this->urls->generate(self::HOME_ROUTE, $query, $referenceType)
            : $this->urls->generate(self::CONTENT_ROUTE, ['path' => ltrim($path, '/'), ...$query], $referenceType);
    }
}
